#!/usr/bin/env python3
"""Render the "YiliGram" wordmark into a VectorDrawable.

Uses Google Sans Flex (SIL OFL 1.1, branding/fonts/) instanced at a bold, fully
rounded setting. The wordmark replaces the upstream "Telegram" text logo shown
in the chat list title and on the intro screen.

    .venv/bin/pip install -r tools/branding/requirements.txt
    .venv/bin/python tools/branding/gen_wordmark.py
"""
import os

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
FONT = os.path.join(ROOT, "branding", "fonts", "GoogleSansFlex.ttf")
OUT = os.path.join(ROOT, "TMessagesProj", "src", "main", "res", "drawable", "yili_wordmark.xml")

TEXT = "YiliGram"
AXES = {"wght": 700, "ROND": 100, "opsz": 36, "wdth": 100, "slnt": 0}
HEIGHT_DP = 20.0  # same visual size as the upstream logo (19–20.4dp)


def main():
    font = instancer.instantiateVariableFont(TTFont(FONT), AXES)
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    kern = None  # GPOS kerning is not applied; the word has no critical pairs.

    upm = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    pen = SVGPathPen(glyph_set)
    bounds = BoundsPen(glyph_set)
    x = 0
    for ch in TEXT:
        name = cmap[ord(ch)]
        # Flip Y: font units grow upwards, VectorDrawable viewport grows downwards.
        t = (1, 0, 0, -1, x, ascent)
        glyph_set[name].draw(TransformPen(pen, t))
        glyph_set[name].draw(TransformPen(bounds, t))
        x += hmtx[name][0]
    xmin, ymin, xmax, ymax = bounds.bounds
    path = pen.getCommands()

    # Translate to the bounding box via a group so path numbers stay compact.
    w, h = xmax - xmin, ymax - ymin
    width_dp = HEIGHT_DP * w / h
    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/branding/gen_wordmark.py from Google Sans Flex (SIL OFL 1.1). Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width_dp:.2f}dp"
    android:height="{HEIGHT_DP:.2f}dp"
    android:viewportWidth="{w:.0f}"
    android:viewportHeight="{h:.0f}">
    <group android:translateX="{-xmin:.0f}" android:translateY="{-ymin:.0f}">
        <path
            android:fillColor="#FFFFFFFF"
            android:pathData="{path}" />
    </group>
</vector>
"""
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(xml)
    print(f"{OUT}: {width_dp:.1f}x{HEIGHT_DP}dp, upm={upm}")


if __name__ == "__main__":
    main()
