export type SceneKey = keyof typeof CONFIG.scenes;
export const SCENE_ORDER: SceneKey[] = [
  'intro', 'expressive', 'customization', 'plugins', 'details', 'push', 'openSource', 'download', 'disclaimer',
];

/** Frame at which each scene starts. */
export const sceneStart = (key: SceneKey): number => {
  let f = 0;
  for (const k of SCENE_ORDER) {
    if (k === key) return f;
    f += Math.round(CONFIG.scenes[k] * CONFIG.fps);
  }
  return f;
};

export const sceneFrames = (key: SceneKey): number => Math.round(CONFIG.scenes[key] * CONFIG.fps);

export const TOTAL_FRAMES = SCENE_ORDER.reduce((n, k) => n + sceneFrames(k), 0);

